function parse(def) {
  const rows = def.map;
  const R = rows.length;
  const C = rows[0].length;
  const at = (r, c) => (r >= 0 && r < R && c >= 0 && c < C ? rows[r][c] : '.');
  const platforms = [];
  const tramps = [];
  const portals = [];
  const pickups = [];
  const spawns = [];
  const respawns = [];
  const letters = {};

  // solid blocks: horizontal runs, merged downwards when the run repeats
  const open = new Map(); // "c0-c1" -> rect still growing
  for (let r = 0; r <= R; r++) {
    const seen = new Set();
    for (let c = 0; c < C; c++) {
      if (at(r, c) !== '#') continue;
      const c0 = c;
      while (at(r, c + 1) === '#') c++;
      const key = `${c0}-${c}`;
      seen.add(key);
      const prev = open.get(key);
      if (prev) prev.h += TILE;
      else {
        const rect = { x: c0 * TILE, y: r * TILE, w: (c - c0 + 1) * TILE, h: TILE, oneway: false, ground: true };
        open.set(key, rect);
        platforms.push(rect);
      }
    }
    for (const key of [...open.keys()]) if (!seen.has(key)) open.delete(key);
  }

  for (let r = 0; r < R; r++) {
    if (rows[r].length !== C) throw new Error(`${def.id}: row ${r} has the wrong length`);
    for (let c = 0; c < C; c++) {
      const ch = rows[r][c];
      if (ch === '=' || ch === '^') {
        const c0 = c;
        while (at(r, c + 1) === ch) c++;
        const x = c0 * TILE;
        const w = (c - c0 + 1) * TILE;
        if (ch === '=') platforms.push({ x, y: r * TILE, w, h: LEDGE_H, oneway: true, ground: false });
        else tramps.push({ x: x + 6, y: (r + 1) * TILE - TRAMP_H, w: w - 12, h: TRAMP_H, cx: x + w / 2 });
      } else if (ch === '*') {
        pickups.push({ x: c * TILE + TILE / 2, y: r * TILE + 18 });
      } else if (ch >= '1' && ch <= '4') {
        spawns[Number(ch) - 1] = [c * TILE + (TILE - PW) / 2, (r + 1) * TILE - PH];
      } else if (ch === 'r') {
        respawns.push([c * TILE + (TILE - PW) / 2, (r + 1) * TILE - PH]);
      } else if (/[A-Za-z]/.test(ch)) {
        const cx = c * TILE + TILE / 2;
        const bottom = (r + 1) * TILE;
        const portal = { x: cx - PORTAL_W / 2, y: bottom - PORTAL_H, w: PORTAL_W, h: PORTAL_H, cx, cy: bottom - PORTAL_H / 2, to: -1, pair: 0 };
        const k = ch.toUpperCase();
        (letters[k] ||= []).push(portals.length);
        portals.push(portal);
      }
    }
  }
  Object.keys(letters)
    .sort()
    .forEach((k, pair) => {
      const [a, b] = letters[k];
      if (b === undefined) throw new Error(`${def.id}: portal ${k} has no partner`);
      portals[a].to = b;
      portals[b].to = a;
      portals[a].pair = portals[b].pair = pair;
    });
  if (spawns.filter(Boolean).length !== 4) throw new Error(`${def.id}: needs spawns 1-4`);

  return {
    id: def.id,
    name: def.name,
    blurb: def.blurb,
    w: C * TILE,
    h: R * TILE,
    platforms,
    tramps,
    portals,
    pickups,
    spawns,
    respawns: respawns.length ? respawns : spawns,
  };
}

export const ARENAS = MAPS.map(parse);
export const ARENA_IDS = ARENAS.map((a) => a.id);

export function arenaById(id) {
  return ARENAS.find((a) => a.id === id) || ARENAS[0];
}
