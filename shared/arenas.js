// Arenas, drawn as text. One character is one 40x40 tile:
//
//   #  solid block: land on top, bump into the sides, bonk your head underneath
//   =  thin ledge: jump up through it, land on it, hold DOWN to drop through
//   ^  trampoline (sits on the tile below it)
//   A/a B/b C/c  portal pairs: walk into one, come out of the other
//   *  a place where power-ups can appear
//   1-4  player start positions      r  where you come back after falling in a pit
//   .  air
//
// Everything is tuned to the movement in config.js: a jump clears 5 tiles, a
// double jump 8, a trampoline 12. The left and right edges of the map are walls.

